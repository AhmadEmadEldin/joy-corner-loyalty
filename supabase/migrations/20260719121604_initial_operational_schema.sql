create extension if not exists citext with schema extensions;

do $$ begin
  create type public.app_role as enum ('owner', 'manager', 'cashier', 'waiter', 'barista', 'customer');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.order_status as enum (
    'draft', 'pending_confirmation', 'confirmed', 'accepted', 'preparing',
    'ready', 'picked_up', 'closed', 'rejected', 'cancelled'
  );
