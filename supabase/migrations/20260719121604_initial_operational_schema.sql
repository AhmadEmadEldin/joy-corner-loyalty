do $$ begin
  create type public.confirmation_status as enum ('not_required', 'pending', 'confirmed', 'rejected', 'cancelled');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.payment_status as enum ('unpaid', 'pending_verification', 'partially_paid', 'paid', 'refunded');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.order_source as enum ('customer_app', 'waiter', 'cashier', 'owner', 'migration');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.payment_method as enum ('cash_at_cashier', 'card_at_branch', 'instapay', 'manual_transfer');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.payment_record_status as enum ('pending', 'confirmed', 'rejected', 'refunded');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.voucher_status as enum ('active', 'reserved', 'redeemed', 'expired', 'cancelled');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.voucher_type as enum ('fixed', 'percentage', 'free_item', 'loyalty_free_drink');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.reward_transaction_type as enum ('earn', 'redeem', 'adjustment', 'migration');
exception when duplicate_object then null; end $$;

