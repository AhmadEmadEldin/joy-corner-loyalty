-- Realtime projection for cashiers. It intentionally excludes profile history,
-- private profile fields, rewards, and lifetime spending.
create table if not exists public.cashier_order_queue (
  order_id uuid primary key references public.orders(id) on delete cascade,
  order_number text not null,
  pickup_name text not null,
  status public.order_status not null,
  confirmation_status public.confirmation_status not null,
  payment_status public.payment_status not null,
  subtotal numeric(12,2) not null,
  discount_total numeric(12,2) not null,
  voucher_discount numeric(12,2) not null,
  tax_total numeric(12,2) not null,
  total numeric(12,2) not null,
  payment_method public.payment_method,
  requested_voucher_id uuid,
  customer_notes text not null default '',
  item_summary jsonb not null default '[]'::jsonb,
