create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name public.app_role not null unique,
  description text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  permission_key text not null unique check (permission_key ~ '^[a-z][a-z0-9_.-]+$'),
  description text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id text unique,
  customer_number text unique,
  full_name text not null check (char_length(trim(full_name)) between 2 and 160),
  phone text,
  email extensions.citext unique,
  role public.app_role not null default 'customer',
  active boolean not null default true,
  date_of_birth date,
  favorite_drink text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_login_at timestamptz,
  constraint profiles_customer_number_role check (
    (role = 'customer' and customer_number is not null)
    or (role <> 'customer')
  ),
  constraint profiles_phone_format check (phone is null or phone ~ '^\+?[0-9]{8,15}$')
);

create unique index if not exists profiles_phone_unique_idx
  on public.profiles (phone) where phone is not null;
create index if not exists profiles_role_active_idx on public.profiles (role, active);
create index if not exists profiles_created_at_idx on public.profiles (created_at desc);

create table if not exists public.role_permissions (
  role_id bigint not null references public.roles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (role_id, permission_id)
);

create table if not exists public.user_permissions (
  user_id uuid not null references public.profiles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  enabled boolean not null,
  granted_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  primary key (user_id, permission_id)
);

create table if not exists public.business_settings (
