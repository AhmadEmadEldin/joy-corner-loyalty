create table if not exists public.vouchers (
  id uuid primary key default extensions.gen_random_uuid(),
  legacy_id text unique,
  voucher_code text not null unique,
  customer_id uuid not null references public.profiles(id) on delete restrict,
  voucher_type public.voucher_type not null,
  fixed_value numeric(12,2) check (fixed_value is null or fixed_value > 0),
  percentage_value numeric(5,2) check (percentage_value is null or percentage_value > 0 and percentage_value <= 100),
  free_item_id uuid references public.menu_items(id) on delete set null,
  status public.voucher_status not null default 'active',
  issued_at timestamptz not null default now(),
  expires_at timestamptz,
  redeemed_at timestamptz,
  redeemed_order_id uuid,
  created_by uuid references public.profiles(id) on delete set null,
  related_reward_transaction_id uuid,
  canva_design_url text,
  qr_token uuid not null default extensions.gen_random_uuid() unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vouchers_value_shape check (
    (voucher_type = 'fixed' and fixed_value is not null)
    or (voucher_type = 'percentage' and percentage_value is not null)
    or (voucher_type in ('free_item', 'loyalty_free_drink') and free_item_id is not null)
  )
);

create index if not exists vouchers_customer_status_idx
  on public.vouchers (customer_id, status, expires_at);
create index if not exists vouchers_code_idx on public.vouchers (voucher_code);

create table if not exists public.orders (
  id uuid primary key default extensions.gen_random_uuid(),
  legacy_id text unique,
  order_number text not null unique,
  customer_id uuid references public.profiles(id) on delete restrict,
  pickup_name text not null,
  source public.order_source not null,
  status public.order_status not null default 'draft',
  confirmation_status public.confirmation_status not null default 'not_required',
  payment_status public.payment_status not null default 'unpaid',
  kitchen_visible boolean not null default false,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount_total numeric(12,2) not null default 0 check (discount_total >= 0),
  voucher_discount numeric(12,2) not null default 0 check (voucher_discount >= 0),
  tax_total numeric(12,2) not null default 0 check (tax_total >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_method public.payment_method,
  requested_voucher_id uuid references public.vouchers(id) on delete set null,
  confirmed_by uuid references public.profiles(id) on delete set null,
  confirmed_at timestamptz,
  assigned_barista_id uuid references public.profiles(id) on delete set null,
  accepted_at timestamptz,
  preparing_at timestamptz,
  ready_at timestamptz,
  picked_up_at timestamptz,
  closed_at timestamptz,
  rejected_at timestamptz,
  rejection_reason text,
  cancelled_at timestamptz,
  cancellation_reason text,
  customer_notes text not null default '',
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_customer_source check (
    (source <> 'customer_app') or customer_id is not null
  ),
  constraint orders_customer_initial_state check (
    source <> 'customer_app'
    or status <> 'pending_confirmation'
    or (confirmation_status = 'pending' and kitchen_visible = false)
  ),
  constraint orders_total_math check (
    total = greatest(0, subtotal - discount_total - voucher_discount + tax_total)
  )
);

